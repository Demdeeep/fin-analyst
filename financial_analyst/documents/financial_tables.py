def _clean(value: object) -> str:
    if value is None:
        return ""
    return re.sub(r"\s+", " ", str(value)).strip()


def _normalize_label(label: str) -> str:
    text = label.casefold().replace("&", " and ")
    text = re.sub(r"[^a-z0-9]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


_NORMALIZED_LABELS = {
    metric: tuple(_normalize_label(label) for label in labels)
    for metric, labels in _LABELS.items()
}


def _metric_for(label: str) -> Optional[str]:
    normalized = _normalize_label(label)
    for metric, candidates in _NORMALIZED_LABELS.items():
        if normalized in candidates:
            return metric
    # Accept a source label with a trailing note marker or unit suffix, but not
    # a different leading concept such as "other operating income".
    for metric, candidates in _NORMALIZED_LABELS.items():
        if any(normalized.startswith(candidate + " ") for candidate in candidates):
            return metric
    return None


def _amount(raw: str) -> Optional[float]:
    text = raw.strip().replace("−", "-").replace("–", "-").replace("—", "-")
    if not text or text in {"-", "--", "n/a", "na", "nm", "—"}:
        return None
    negative = text.startswith("(") and text.endswith(")")
    if negative:
        text = text[1:-1]
    text = text.replace(",", "").replace("$", "").replace("€", "").replace("£", "")
    text = re.sub(r"\s+", "", text)
    text = re.sub(r"[*†‡¹²³]+$", "", text)
    if not _NUMERIC.fullmatch(text):
        return None
    value = float(text)
    return -abs(value) if negative else value


def _statement_kind(page_text: str) -> Optional[str]:
    text = _normalize_label(page_text)
    if "balance sheets" in text or "statement of financial position" in text:
        return "balance_sheet"
    if "cash flows" in text or "cashflow" in text:
        return "cash_flow_statement"
    if any(term in text for term in ("statements of operations", "statements of income", "income statement", "statements of earnings")):
        return "income_statement"
    return None


def _unit(page_text: str, rows: tuple[tuple[str, ...], ...]) -> tuple[str, Optional[float]]:
    context = _normalize_label(page_text + " " + " ".join(cell for row in rows[:4] for cell in row))
    # SEC statements often say money is in millions while share counts are in
    # thousands. Prefer the monetary heading so share qualifiers cannot scale
    # every dollar line down by 1,000.
    if "in millions" in context or "amounts in millions" in context:
        return "USD millions as reported", 1.0
    if "in thousands" in context or "amounts in thousands" in context:
        return "USD thousands as reported", 0.001
    return "unit not identified", None


def _year_columns(rows: tuple[tuple[str, ...], ...]) -> tuple[int, dict[int, int]]:
    best_row = -1
    best: dict[int, int] = {}
    for row_index, row in enumerate(rows[:8]):
        columns: dict[int, int] = {}
        for column_index, cell in enumerate(row):
            match = _YEAR.search(cell)
            if match:
                columns[column_index] = int(match.group(0))
        if len(columns) > len(best):
            best_row, best = row_index, columns
    return best_row, best


def _extract_table_values(
    rows: tuple[tuple[str, ...], ...],
    *,
    page_number: int,
    table_number: int,
    unit: str,
    unit_scale: Optional[float],
) -> tuple[FinancialValue, ...]:
    header_index, year_columns = _year_columns(rows)
    if header_index < 0 or not year_columns:
        return ()

    values: list[FinancialValue] = []
    for row in rows[header_index + 1:]:
        label_index = next((i for i, cell in enumerate(row) if cell), None)
        if label_index is None:
            continue
        label = row[label_index]
        metric = _metric_for(label)
        if metric is None:
            continue
        for column_index, year in year_columns.items():
            if column_index >= len(row):
                continue
            raw = row[column_index]
            amount = _amount(raw)
            if amount is None:
                continue
            values.append(FinancialValue(
                metric=metric,
                label_in_pdf=label,
                fiscal_year=year,
                reported_value=amount,
                raw_value=raw,
                reported_unit=unit,
                usd_millions=(amount * unit_scale if unit_scale is not None else None),
                page=page_number,
                table=table_number,
            ))
    return tuple(values)


_TRAILING_AMOUNTS = re.compile(
    r"(?P<amounts>(?:\s+(?:\(?-?\$?\s?\d[\d,]*(?:\.\d+)?\)?|[-–—])){2,})\s*$"
)
_TEXT_AMOUNT = re.compile(r"\(?-?\$?\s?\d[\d,]*(?:\.\d+)?\)?|[-–—]")


def _extract_text_rows(
    page_text: str, *, page_number: int, unit: str, unit_scale: Optional[float],
) -> tuple[tuple[tuple[str, ...], ...], tuple[FinancialValue, ...]]:
    """Read simple financial rows when PDF table borders/layout are missing.

    This is deliberately conservative: a row must have a recognized label,
    multiple trailing numeric cells, and a same-page multi-year header.
    """
    lines = [re.sub(r"\s+", " ", line).strip() for line in page_text.splitlines()]
    year_header: list[int] = []
    seen_years: set[int] = set()
    for line in lines:
        years = [int(match.group()) for match in _YEAR.finditer(line)]
        for year in years:
            if year not in seen_years:
                seen_years.add(year)
                year_header.append(year)
        if len(year_header) >= 3:
            break
    if len(year_header) < 2:
        year_header = []
    if not year_header:
        return (), ()

    rows: list[tuple[str, ...]] = [("", *(str(year) for year in year_header))]
    values: list[FinancialValue] = []
    non_current_liabilities = False
    in_current_liabilities = False
    for line in lines:
        match = _TRAILING_AMOUNTS.search(line)
        if not match:
            if _normalize_label(line) == "non current liabilities":
                non_current_liabilities = True
                in_current_liabilities = False
            elif _normalize_label(line) == "current liabilities":
                non_current_liabilities = False
                in_current_liabilities = True
            continue
        label = line[:match.start()].strip(" .:\t")
        metric = _metric_for(label)
        if _normalize_label(label) == "term debt":
            metric = "long_term_debt" if non_current_liabilities else (
                "short_term_debt" if in_current_liabilities else None
            )
        if metric is None:
            continue
        raw_values = _TEXT_AMOUNT.findall(match.group("amounts"))
        if len(raw_values) < 2:
            continue
        rows.append((label, *raw_values))
        for year, raw in zip(year_header, raw_values):
            amount = _amount(raw)
            if amount is None:
                continue
            values.append(FinancialValue(
                metric=metric,
                label_in_pdf=label,
                fiscal_year=year,
                reported_value=amount,
                raw_value=raw,
                reported_unit=unit,
                usd_millions=(amount * unit_scale if unit_scale is not None else None),
                page=page_number,
                table=0,
            ))
    return tuple(rows), tuple(values)


def extract_financial_tables(data: bytes, *, max_bytes: int = 25_000_000) -> list[FinancialTable]:
    """Extract recognizable statement tables locally from a searchable PDF."""
    if not data or not data.startswith(b"%PDF-"):
        raise FinancialTableExtractionError("This file does not appear to be a valid PDF.")
    if len(data) > max_bytes:
        raise FinancialTableExtractionError("PDFs must be 25 MB or smaller.")
    try:
        import pdfplumber
    except ImportError as error:
        raise FinancialTableExtractionError(
            "Financial table extraction is not installed. Run: python -m pip install -e '.[pdf]'"
        ) from error

    extracted: list[FinancialTable] = []
    try:
        with pdfplumber.open(BytesIO(data)) as pdf:
            for page_number, page in enumerate(pdf.pages, start=1):
                page_text = page.extract_text() or ""
                statement = _statement_kind(page_text)
                if statement is None:
                    continue
                raw_tables = page.extract_tables() or []
                for table_number, raw_table in enumerate(raw_tables, start=1):
                    rows = tuple(
                        tuple(_clean(cell) for cell in row)
                        for row in raw_table
                    )
                    if not rows:
                        continue
                    unit, scale = _unit(page_text, rows)
                    values = _extract_table_values(
                        rows, page_number=page_number, table_number=table_number,
                        unit=unit, unit_scale=scale,
                    )
                    if values:
                        extracted.append(FinancialTable(
                            page=page_number,
                            table=table_number,
                            statement=statement,
                            reported_unit=unit,
                            rows=rows,
                            values=values,
                        ))
                if not any(table.page == page_number for table in extracted):
                    unit, scale = _unit(page_text, ())
                    text_rows, text_values = _extract_text_rows(
                        page_text, page_number=page_number,
                        unit=unit, unit_scale=scale,
                    )
                    if text_values:
                        extracted.append(FinancialTable(
                            page=page_number,
                            table=0,
                            statement=statement,
                            reported_unit=unit,
                            rows=text_rows,
                            values=text_values,
                        ))
    except FinancialTableExtractionError:
        raise
    except Exception as error:
        raise FinancialTableExtractionError("Could not extract financial tables from this PDF.") from error

    return extracted


def compare_with_stage1(
    values: Iterable[FinancialValue], metrics_frame, ticker: str,
) -> list[dict]:
    """Create a review-only side-by-side comparison with matching Stage 1 rows.

    The 0.05 USD-million / 0.05% tolerance accounts for common statement
    rounding. A status never substitutes for checking the source presentation.
    """
    results: list[dict] = []
    ticker_rows = metrics_frame[metrics_frame["ticker"] == ticker]
    for value in values:
        stage1_name = _STAGE1_METRICS.get(value.metric)
        match = ticker_rows[ticker_rows["fiscal_year"] == value.fiscal_year]
        base = {
            "ticker": ticker,
            "fiscal_year": value.fiscal_year,
            "metric": value.metric,
            "pdf_value_usd_millions": value.usd_millions,
            "page": value.page,
            "table": value.table,
        }
        if value.usd_millions is None:
            results.append({**base, "stage1_value_usd_millions": None, "difference": None,
                            "status": "unit unclear; not compared"})
            continue
        if stage1_name is None:
            results.append({**base, "stage1_value_usd_millions": None, "difference": None,
                            "status": "metric not carried by Stage 1"})
            continue
        if match.empty:
            results.append({**base, "stage1_value_usd_millions": None, "difference": None,
                            "status": "no matching ticker and year in Stage 1"})
            continue
        expected = match.iloc[0].get(stage1_name)
        if pd_is_missing(expected):
            results.append({**base, "stage1_value_usd_millions": None, "difference": None,
                            "status": "Stage 1 value unavailable"})
            continue
        expected = float(expected)
        difference = value.usd_millions - expected
        tolerance = max(0.05, abs(expected) * 0.0005)
        results.append({
            **base,
            "stage1_value_usd_millions": expected,
            "difference": difference,
            "status": "within rounding tolerance" if abs(difference) <= tolerance else "review difference",
        })
    return results


