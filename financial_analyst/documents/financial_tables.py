"""Local, rule-based extraction of financial statement rows from PDF tables.

This intentionally returns source values with page and table references. It
does not guess missing years, infer units, or claim that the extracted values
are correct.
"""

from __future__ import annotations

import re
from dataclasses import asdict, dataclass
from io import BytesIO
from typing import Iterable, Optional


class FinancialTableExtractionError(ValueError):
    """A PDF could not be searched for structured financial tables."""


@dataclass(frozen=True)
class FinancialValue:
    metric: str
    label_in_pdf: str
    fiscal_year: int
    reported_value: float
    raw_value: str
    reported_unit: str
    usd_millions: Optional[float]
    page: int
    table: int

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass(frozen=True)
class FinancialTable:
    page: int
    table: int
    statement: str
    reported_unit: str
    rows: tuple[tuple[str, ...], ...]
    values: tuple[FinancialValue, ...]


