def make_stage1_csv_rows(
    values: Iterable[FinancialValue], *, ticker: str, company_name: str,
    currency: str = "USD", sector: str = "",
) -> tuple[list[dict], list[str]]:
    """Shape extracted PDF values into Stage 1's CSV schema for manual review.

    Missing/unmapped values remain blank. Duplicate metric/year values are
    deliberately omitted and reported for manual resolution.
    """
    by_year: dict[int, list[FinancialValue]] = {}
    for value in values:
        by_year.setdefault(value.fiscal_year, []).append(value)

    rows: list[dict] = []
    notes: list[str] = []
    for year, year_values in sorted(by_year.items()):
        row = {column: None for column in STAGE1_CSV_COLUMNS}
        row.update({
            "ticker": ticker.strip().upper(),
            "company_name": company_name.strip(),
            "sector": sector.strip(),
            "fiscal_year": year,
            "currency": currency,
            "source": "PDF extraction, page(s) " + ", ".join(
                str(page) for page in sorted({value.page for value in year_values})
            ) + "; verify against filing",
        })
        found: dict[str, list[float]] = {}
        for value in year_values:
            destination = _STAGE1_METRICS.get(value.metric)
            if destination and value.usd_millions is not None:
                found.setdefault(destination, []).append(value.usd_millions)
        for destination, extracted in found.items():
            if len(extracted) > 1:
                if destination == "short_term_debt":
                    # Apple-style balance sheets list current borrowings by
                    # component (for example, commercial paper and term debt).
                    row[destination] = sum(extracted)
                else:
                    notes.append(f"FY{year} {destination}: multiple extracted values; left blank for manual review")
            elif not destination.startswith("_"):
                row[destination] = extracted[0]

        # Stage 1 represents capital expenditure as a positive cash-outflow amount.
        if row["capex"] is not None:
            row["capex"] = abs(row["capex"])
        research = found.get("_research_and_development", [])
        selling_admin = found.get("_selling_general_and_administrative", [])
        if len(research) == 1 and len(selling_admin) == 1:
            row["operating_expenses"] = research[0] + selling_admin[0]
        rows.append(row)

    required_value_columns = {
        "revenue", "cogs", "gross_profit", "operating_expenses", "operating_income",
        "interest_expense", "pretax_income", "tax_expense", "net_income", "diluted_shares",
        "cash_and_equivalents", "inventory", "total_current_assets", "total_assets",
        "short_term_debt", "total_current_liabilities", "long_term_debt", "total_liabilities",
        "total_equity", "cash_from_operations", "capex",
    }
    missing = sorted(column for column in required_value_columns
                     if not any(row[column] is not None for row in rows))
    if missing:
        notes.append("Required Stage 1 fields left blank: " + ", ".join(missing))
    return rows, notes


def pd_is_missing(value: object) -> bool:
    """Avoid importing pandas into the PDF parser's module-level path."""
    if value is None:
        return True
    try:
        import math

        return math.isnan(float(value))
    except (TypeError, ValueError):
        return False
