"""The prose templates, kept as data rather than as f-strings inside code.

Keeping them here means a reviewer can read every sentence the system can
possibly emit without reading a single line of logic -- which is the only
practical way to keep generated text free of unwarranted conclusions.

Every placeholder is filled by :mod:`financial_analyst.reporting.summary`, and
the test suite fails if any ``{placeholder}`` survives into the output.

No template contains a conclusion. "Net margin fell 9.4pp" is a fact;
"net margin is underperforming" is a judgement, and judgements are Stage 2's
job. See ``BANNED_WORDS`` in the test suite, which enforces this mechanically.
"""

