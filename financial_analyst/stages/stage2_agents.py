"""Stage 2: LLM agents over Stage 1's artifacts.

    outputs/stage1_metrics.json ─┐
    outputs/stage1_flags.csv    ─┴─► analyst ─► critic ─► outputs/stage2_*.json/md

Run it with no API key and the deterministic stub produces a visibly mechanical
narrative, which is the point: the pipeline, the prompts, the tool loop and the
verification all execute end to end, and the only thing a key changes is prose
quality.

    python -m financial_analyst.stages.stage2_agents
    python -m financial_analyst.stages.stage2_agents --provider openai --ticker INIT
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Optional

import pandas as pd

from .. import config
from ..agents.orchestrator import Orchestrator, Stage2Result
from ..agents.critic import REJECT
from ..agents.flags import load_flag_refs
from ..agents.providers import build_client, describe
from ..agents.tools import MetricStore

OUTPUT_STAGE2_JSON = "stage2_analysis.json"
OUTPUT_STAGE2_MD = "stage2_analysis.md"


def load_flags(path: Path) -> dict[str, list[str]]:
    """Pre-rendered flag lines, for callers that only need text.

    The structured path is :func:`financial_analyst.agents.flags.load_flag_refs`;
    this stays because a test or a hand-written brief may want the same wording
    without the record type.
    """
    return {
        ticker: [flag.render() for flag in flags]
        for ticker, flags in load_flag_refs(path).items()
    }


def render_report(results: list[Stage2Result], provider: str) -> str:
    """A markdown view of the run, for a reader who will not open the JSON."""
    verified = sum(1 for result in results if result.verified)
    lines = [
        "# Stage 2 agent analysis",
        "",
        f"Provider: `{provider}`. {len(results)} companies, {verified} with "
        "every figure reconciling against Stage 1.",
        "",
        "Stage 1 states values without judging them; the judgement is here, and "
        "every number below is checked against Stage 1's output.",
        "",
    ]
    for result in results:
        coverage = (
            f" — flags addressed {result.flags_addressed}/{result.flags_considered}"
            if result.flags_considered else ""
        )
        retry = "" if result.verdict != REJECT else (
            "" if result.retryable else " (not retryable)"
        )
        lines += [
            f"## {result.ticker}",
            "",
            f"Verdict: **{result.verdict}**{retry}"
            + (" — all figures verified" if result.verified else "") + coverage
            + (f" · {result.revisions} revision(s)" if result.revisions else ""),
            "",
            result.narrative,
            "",
        ]
        if result.tools_requested:
            lines += ["Metrics used: " + ", ".join(result.tools_requested), ""]
        if result.issues:
            lines.append("Unverified figures:")
            lines += [f"- {issue}" for issue in result.issues]
            lines.append("")
        unaddressed = [item for item in result.coverage if item.needs_review]
        if unaddressed:
            lines.append(f"Flags not addressed ({len(unaddressed)}):")
            lines += [f"- {item}" for item in unaddressed]
            lines.append("")
        if result.critic_notes:
            lines += [f"Critic: {result.critic_notes}", ""]
    lines += [
        "---",
        "",
        "Generated by Stage 2. Figures are checked mechanically against Stage 1; "
        "a verdict of OK means the numbers reconcile and the reasoning was "
        "reviewed, not that the conclusion is correct.",
        "",
    ]
    return "\n".join(lines)


def run_stage2(
    metrics_path: Optional[Path] = None,
    flags_path: Optional[Path] = None,
    output_dir: Optional[Path] = None,
    provider: str = "stub",
    tickers: Optional[list[str]] = None,
    consult_critic_model: bool = True,
    write: bool = True,
) -> list[Stage2Result]:
    """Analyse every company in Stage 1's metrics, or just ``tickers``."""
    metrics_path = Path(metrics_path or config.OUTPUT_METRICS_JSON)
    flags_path = Path(flags_path or config.OUTPUT_FLAGS_CSV)
    if not metrics_path.exists():
        raise FileNotFoundError(
            f"{metrics_path} not found -- run Stage 1 first "
            f"(python -m financial_analyst.stages.stage1_static_csv)"
        )

    store = MetricStore.from_json(metrics_path)
    if store.empty:
        raise ValueError(f"{metrics_path} contains no companies")

    flags_by_ticker = load_flag_refs(flags_path)
    client = build_client(provider)
    orchestrator = Orchestrator(client, store, consult_critic_model=consult_critic_model)

    selected = tickers or list(store.tickers)
    results = [
        orchestrator.run(ticker, flags=flags_by_ticker.get(ticker, ()))
        for ticker in selected
    ]

    if write:
        destination = Path(output_dir) if output_dir else config.OUTPUT_DIR
        destination.mkdir(parents=True, exist_ok=True)
        payload = {
            "provider": provider,
            "companies": [result.to_dict() for result in results],
        }
        (destination / OUTPUT_STAGE2_JSON).write_text(
            json.dumps(payload, indent=2) + "\n"
        )
        (destination / OUTPUT_STAGE2_MD).write_text(render_report(results, provider))
    return results


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Stage 2 agent analysis")
    parser.add_argument(
        "--provider", default="stub", choices=("stub", "openai", "auto"),
        help="'auto' uses OpenAI when a key is configured, else the stub",
    )
    parser.add_argument("--ticker", action="append", dest="tickers",
                        help="limit to one ticker; repeatable")
    parser.add_argument("--no-critic-model", action="store_true",
                        help="rely on the mechanical check only")
    parser.add_argument("--no-write", action="store_true")
    parser.add_argument("--verbose", action="store_true",
                        help="print critic findings and unresolved flags")
    parser.add_argument("--dotenv", default=None,
                        help="path to a .env file holding OPENAI_API_KEY")
    arguments = parser.parse_args(argv)

    # Print the provider before any call is made. `--provider auto` with no key
    # silently produces stub output, and a finished-looking report written by a
    # placeholder is the worst outcome of a mistyped flag.
    if arguments.dotenv is not None:
        from ..agents.providers.base import load_dotenv

        if not load_dotenv(arguments.dotenv):
            print(f"warning: {arguments.dotenv} not found", file=sys.stderr)
    print(f"provider: {describe(arguments.provider)}", file=sys.stderr)

    results = run_stage2(
        provider=arguments.provider,
        tickers=arguments.tickers,
        consult_critic_model=not arguments.no_critic_model,
        write=not arguments.no_write,
    )
    for result in results:
        print(
            f"{result.ticker:6} {result.verdict:6} "
            f"verified={result.verified} revisions={result.revisions}"
        )
        if arguments.verbose:
            debug_cause = (
                "numerified_undefined" if any(getattr(issue, "kind", "") == "numerified_undefined" for issue in result.issues)
                else "unresolved_flag" if any(item.needs_review and getattr(item.flag, "must_address", False) for item in result.coverage)
                else "figure_issue" if result.issues
                else "model_only" if result.verdict == "REVISE"
                else "none"
            )
            print(f"  debug_first_verdict_cause: {debug_cause}")
            print("  narrative:")
            print(f"  {result.narrative}")
            if result.issues:
                print("  issues:")
                for issue in result.issues:
                    print(f"  - {issue}")
            unresolved = [item for item in result.coverage if item.needs_review]
            if unresolved:
                print("  unaddressed_flags:")
                for item in unresolved:
                    print(f"  - {item}")
            if result.critic_notes:
                print(f"  critic_notes: {result.critic_notes}")
    return 0


if __name__ == "__main__":
    sys.exit(main())